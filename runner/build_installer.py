"""Regenerate install-runner.sh from the source files so the installer never drifts.
Run: python3 runner/build_installer.py"""

from pathlib import Path

HERE = Path(__file__).parent
EOF_MARK = "AGENTRUSH_EOF"

FILES = {
    "/opt/agentrush-runner/app.py": HERE / "app.py",
    "/opt/agentrush-runner/sandbox.Dockerfile": HERE / "sandbox.Dockerfile",
    "/opt/agentrush-runner/browser/driver.py": HERE / "browser" / "driver.py",
    "/opt/agentrush-runner/browser/Dockerfile": HERE / "browser" / "Dockerfile",
    "/opt/agentrush-runner/egress/proxy.py": HERE / "egress" / "proxy.py",
    "/opt/agentrush-runner/egress/Dockerfile": HERE / "egress" / "Dockerfile",
    "/etc/systemd/system/agentrush-runner.service": HERE / "agentrush-runner.service",
}


def heredoc(dest: str, src: Path) -> str:
    text = src.read_text()
    assert EOF_MARK not in text, src
    if not text.endswith("\n"):
        text += "\n"
    return f"cat > {dest} <<'{EOF_MARK}'\n{text}{EOF_MARK}\n"


body = "\n".join(heredoc(d, s) for d, s in FILES.items())

script = f'''#!/usr/bin/env bash
# Agent Rush - sandbox runner installer for the executor VM (VM 2).
# Run as root. Safe to re-run: keeps the existing token.
# Generated by runner/build_installer.py - edit the source files, not this script.
set -euo pipefail

echo "==> Installing Python venv support"
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq && apt-get install -y -qq python3-venv python3-pip openssl >/dev/null

echo "==> Writing runner files"
mkdir -p /opt/agentrush-runner/browser /opt/agentrush-runner/egress /etc/agentrush /var/lib/agentrush/jobs
chmod 711 /var/lib/agentrush /var/lib/agentrush/jobs

{body}
echo "==> Creating Python environment"
python3 -m venv /opt/agentrush-runner/venv
/opt/agentrush-runner/venv/bin/pip install -q --upgrade pip
/opt/agentrush-runner/venv/bin/pip install -q fastapi "uvicorn[standard]" pydantic

echo "==> Building sandbox image (pandas, matplotlib, ...)"
docker build -q -t agentrush-sandbox:latest -f /opt/agentrush-runner/sandbox.Dockerfile /opt/agentrush-runner >/dev/null
echo "==> Building egress proxy image"
docker build -q -t agentrush-egress:latest /opt/agentrush-runner/egress >/dev/null
echo "==> Building browser image (Chromium + Playwright) - takes 3-6 minutes the first time"
docker build -q -t agentrush-browser:latest /opt/agentrush-runner/browser >/dev/null

echo "==> Detecting private (VPC) IP"
PRIV_IP=$(ip -4 -o addr show | awk '$2 !~ /^(docker|br-|lo|veth)/ {{print $4}}' | cut -d/ -f1 | grep -E '^10\\.' | head -1 || true)
if [ -z "$PRIV_IP" ]; then
  echo "ERROR: no 10.x private IP found. Is VPC attached?" >&2
  exit 1
fi

if [ -f /etc/agentrush/runner.env ] && grep -q '^RUNNER_TOKEN=' /etc/agentrush/runner.env; then
  TOKEN=$(grep '^RUNNER_TOKEN=' /etc/agentrush/runner.env | cut -d= -f2-)
else
  TOKEN=$(openssl rand -hex 32)
fi

cat > /etc/agentrush/runner.env <<{EOF_MARK}
RUNNER_TOKEN=$TOKEN
RUNNER_BIND=$PRIV_IP
SANDBOX_IMAGE=agentrush-sandbox:latest
BROWSER_IMAGE=agentrush-browser:latest
EGRESS_IMAGE=agentrush-egress:latest
DOCKER_RUNTIME=runsc
JOBS_DIR=/var/lib/agentrush/jobs
MAX_CONCURRENT=2
{EOF_MARK}
chmod 600 /etc/agentrush/runner.env

echo "==> Starting service"
systemctl daemon-reload
systemctl enable -q agentrush-runner
systemctl restart agentrush-runner
sleep 3

echo "==> Health check"
curl -s "http://$PRIV_IP:8080/health" && echo

echo
echo "=================================================================="
echo " Runner is listening ONLY on the private network: http://$PRIV_IP:8080"
echo " RUNNER_TOKEN (copy into your notes; never commit it):"
echo "   $TOKEN"
echo "=================================================================="
'''

(HERE / "install-runner.sh").write_text(script)
print(f"install-runner.sh written ({len(script.splitlines())} lines)")
